<?php
/**
 * Module:      output_beer_xml_new.inc.php
 * Description: Export a single BrewBlog (brewblogs table) as a BeerXML 1.0 file.
 *
 * Ingredient, mash, equipment, and water data are stored as JSON using BeerXML
 * tag names, but numeric values were converted to the site's unit preferences
 * on import (see convertUnit() in admin/includes/upload_xml_new.inc.php).
 * BeerXML requires metric, so those values are converted back here using the
 * current preferences.
 */

require ('../paths.php');
require (CONFIG.'config.php');
include (INCLUDES.'db_connect_universal.inc.php');
include (INCLUDES.'url_variables.inc.php');
include (LIB.'common.lib.php');

if ((!isset($_GET['id'])) || (!is_numeric($_GET['id']))) {
    echo "Not a valid request.";
    die;
}

$query_log = sprintf("SELECT * FROM brewblogs WHERE id = '%s'", (int) $_GET['id']);
$log = mysqli_query($connection,$query_log) or die (mysqli_error($connection));
$row_log = mysqli_fetch_assoc($log);

if (!$row_log) {
    echo "Not a valid request.";
    die;
}

$query_brewer = sprintf("SELECT realFirstName, realLastName FROM users WHERE user_name = '%s'", mysqli_real_escape_string($connection, (string) $row_log['brewBrewerID']));
$brewer = mysqli_query($connection,$query_brewer) or die (mysqli_error($connection));
$row_brewer = mysqli_fetch_assoc($brewer);

// Reverse of convertUnit() in upload_xml_new.inc.php: site units back to BeerXML metric
function beer_xml_metric($value, $type) {

    if (!is_numeric($value)) return $value;
    $value = (float) $value;

    switch ($type) {
        case "hopWeight":
            if ($_SESSION['measWeight1'] == "grams") return round($value / 1000, 6);
            else return round($value / 35.27396, 6);
        case "temperature":
            if ($_SESSION['measTemp'] == "F") return round(($value - 32) / 1.8, 2);
            else return round($value, 2);
        case "volume":
            if ($_SESSION['measFluid2'] == "gallons") return round($value / 0.26417, 6);
            else return round($value, 6);
        case "weight":
            if ($_SESSION['measWeight2'] == "pounds") return round($value / 2.20462, 6);
            else return round($value, 6);
    }

    return $value;

}

// Values are stored HTML-encoded (sterilize/htmlspecialchars); decode, then encode for XML
function beer_xml_tag($tag, $value, $indent) {
    $value = html_entity_decode(strip_tags((string) $value), ENT_QUOTES | ENT_HTML5, 'UTF-8');
    return str_repeat("\t", $indent)."<".$tag.">".htmlspecialchars($value, ENT_XML1 | ENT_QUOTES, 'UTF-8')."</".$tag.">\n";
}

// Output one JSON-decoded record; $conversions maps tag names to a beer_xml_metric() type
function beer_xml_record($tag, $record, $conversions, $indent) {

    if (!is_array($record)) return "";

    $output = str_repeat("\t", $indent)."<".$tag.">\n";

    foreach ($record as $key => $value) {

        if (is_array($value)) continue;

        $type = $conversions[$key] ?? "";
        // Misc and yeast amounts are weights or volumes depending on AMOUNT_IS_WEIGHT
        if ($type == "amount") $type = ((isset($record['AMOUNT_IS_WEIGHT'])) && (strtoupper($record['AMOUNT_IS_WEIGHT']) == "TRUE")) ? "weight" : "volume";
        if (!empty($type)) $value = beer_xml_metric($value, $type);

        $output .= beer_xml_tag($key, $value, $indent + 1);

    }

    $output .= str_repeat("\t", $indent)."</".$tag.">\n";

    return $output;

}

// Output a group of records (e.g., FERMENTABLES > FERMENTABLE)
function beer_xml_group($group_tag, $tag, $json, $conversions, $indent) {

    $records = json_decode((string) $json, true);
    if (empty($records) || !is_array($records)) return "";

    $output = str_repeat("\t", $indent)."<".$group_tag.">\n";
    foreach ($records as $record) $output .= beer_xml_record($tag, $record, $conversions, $indent + 1);
    $output .= str_repeat("\t", $indent)."</".$group_tag.">\n";

    return $output;

}

$xml_output = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n";
$xml_output .= "<!-- BeerXML Format Generated by BrewBlogger, browser-based brew log and calculation software, http://www.brewblogger.net -->\n";
$xml_output .= "<RECIPES>\n";
$xml_output .= "\t<RECIPE>\n";

$xml_output .= beer_xml_tag("NAME", $row_log['brewName'], 2);
$xml_output .= beer_xml_tag("VERSION", "1", 2);
$xml_output .= beer_xml_tag("TYPE", $row_log['brewMethod'], 2);
if ($row_brewer) $xml_output .= beer_xml_tag("BREWER", trim($row_brewer['realFirstName']." ".$row_brewer['realLastName']), 2);
else $xml_output .= beer_xml_tag("BREWER", $row_log['brewBrewerID'], 2);
$xml_output .= beer_xml_tag("BATCH_SIZE", beer_xml_metric($row_log['brewBatchSize'], "volume"), 2);
$xml_output .= beer_xml_tag("BOIL_SIZE", beer_xml_metric($row_log['brewBoilSize'], "volume"), 2);
$xml_output .= beer_xml_tag("BOIL_TIME", $row_log['brewBoilTime'], 2);
$xml_output .= beer_xml_tag("EFFICIENCY", $row_log['brewEfficiency'], 2);
$xml_output .= beer_xml_tag("NOTES", $row_log['brewInfo'], 2);
$xml_output .= beer_xml_tag("TASTE_NOTES", $row_log['brewComments'], 2);
$xml_output .= beer_xml_tag("OG", $row_log['brewOG'], 2);
$xml_output .= beer_xml_tag("FG", $row_log['brewFG'], 2);
$xml_output .= beer_xml_tag("IBU", $row_log['brewIBU'], 2);
$xml_output .= beer_xml_tag("EST_COLOR", $row_log['brewColor'], 2);
$xml_output .= beer_xml_tag("EST_ABV", $row_log['brewABV'], 2);
$xml_output .= beer_xml_tag("CARBONATION", $row_log['brewCarbonation'], 2);
if (is_numeric($row_log['brewDate'])) $xml_output .= beer_xml_tag("DATE", date("Y-m-d", (int) $row_log['brewDate']), 2);

// Fermentation stages are stored as {"PRIMARY_AGE":..,"PRIMARY_TEMP":..}, etc.
foreach (array('brewPrimary', 'brewSecondary', 'brewTertiary', 'brewAge') as $stage_column) {
    $stage = json_decode((string) $row_log[$stage_column], true);
    if (!is_array($stage)) continue;
    foreach ($stage as $key => $value) {
        if (substr($key, -5) == "_TEMP") $value = beer_xml_metric($value, "temperature");
        $xml_output .= beer_xml_tag($key, $value, 2);
    }
}

$style = json_decode((string) $row_log['brewStyle'], true);
if (is_array($style)) $xml_output .= beer_xml_record("STYLE", $style, array(), 2);

$xml_output .= beer_xml_group("FERMENTABLES", "FERMENTABLE", $row_log['brewFermentables'], array('AMOUNT' => "weight"), 2);
$xml_output .= beer_xml_group("HOPS", "HOP", $row_log['brewHops'], array('AMOUNT' => "hopWeight", 'HOP_TEMP' => "temperature", 'TEMPERATURE' => "temperature"), 2);
$xml_output .= beer_xml_group("MISCS", "MISC", $row_log['brewMiscs'], array('AMOUNT' => "amount"), 2);
// Yeast MIN/MAX_TEMPERATURE are already stored in Celsius
$xml_output .= beer_xml_group("YEASTS", "YEAST", $row_log['brewYeasts'], array('AMOUNT' => "amount"), 2);
$xml_output .= beer_xml_group("WATERS", "WATER", $row_log['brewWater'], array('AMOUNT' => "volume"), 2);

$equipment = json_decode((string) $row_log['brewEquipment'], true);
if (is_array($equipment)) {
    $equipment_volumes = array('BOIL_SIZE', 'BATCH_SIZE', 'TUN_VOLUME', 'TOP_UP_WATER', 'TRUB_CHILLER_LOSS', 'LAUTER_DEADSPACE', 'TOP_UP_KETTLE');
    $xml_output .= beer_xml_record("EQUIPMENT", $equipment, array_fill_keys($equipment_volumes, "volume") + array('TUN_WEIGHT' => "weight"), 2);
}

$mash = json_decode((string) $row_log['brewMash'], true);
if (is_array($mash)) {
    $mash_record = beer_xml_record("MASH", $mash, array('GRAIN_TEMP' => "temperature", 'TUN_TEMP' => "temperature", 'SPARGE_TEMP' => "temperature", 'TUN_WEIGHT' => "weight"), 2);
    if ((isset($mash['MASH_STEPS'])) && (is_array($mash['MASH_STEPS']))) {
        $mash_steps = "\t\t\t<MASH_STEPS>\n";
        foreach ($mash['MASH_STEPS'] as $mash_step) $mash_steps .= beer_xml_record("MASH_STEP", $mash_step, array('STEP_TEMP' => "temperature", 'END_TEMP' => "temperature"), 4);
        $mash_steps .= "\t\t\t</MASH_STEPS>\n";
        $mash_record = str_replace("\t\t</MASH>\n", $mash_steps."\t\t</MASH>\n", $mash_record);
    }
    $xml_output .= $mash_record;
}

$xml_output .= "\t</RECIPE>\n";
$xml_output .= "</RECIPES>\n";

$filename = pathauto_cleanstring($row_log['brewName']);
if (empty($filename)) $filename = "brewblog-".$row_log['id'];

header("Content-Type: application/xml; charset=UTF-8");
header("Content-Disposition: attachment; filename=".$filename.".xml");
header("Pragma: no-cache");
header("Expires: 0");
echo $xml_output;
?>
